import type { Genre, Movie, ProviderId, SeasonSummary, Series, Title } from "@/domain/types";

/**
 * Demo catalog used by the seed data source and by the database seed script.
 * In production these records come from a CatalogService (e.g. TMDB) and are
 * cached in the `titles` table; the UI never imports this file.
 */

type Palette = readonly [string, string, string];

function movie(
  id: string,
  title: string,
  year: number,
  runtimeMinutes: number,
  genres: Genre[],
  providers: ProviderId[],
  communityRating: number,
  palette: Palette,
  overview: string,
): Movie {
  return {
    id,
    type: "movie",
    title,
    year,
    runtimeMinutes,
    genres,
    providers,
    communityRating,
    overview,
    artwork: { posterUrl: null, backdropUrl: null, palette },
  };
}

function show(
  type: "series" | "anime",
  id: string,
  title: string,
  year: number,
  seasons: number[],
  episodeRuntimeMinutes: number,
  genres: Genre[],
  providers: ProviderId[],
  communityRating: number,
  palette: Palette,
  overview: string,
): Series {
  const seasonSummaries: SeasonSummary[] = seasons.map((episodeCount, i) => ({
    number: i + 1,
    episodeCount,
  }));
  return {
    id,
    type,
    title,
    year,
    seasons: seasonSummaries,
    episodeRuntimeMinutes,
    genres,
    providers,
    communityRating,
    overview,
    artwork: { posterUrl: null, backdropUrl: null, palette },
  };
}

